#!/usr/bin/env python3
"""
Chapter 2: Python Basics
Example 12: Assignment Operators
"""

# Basic assignment
x = 10
print("x =", x)

# Add and assign
x += 5  # Same as: x = x + 5
print("After x += 5:", x)  # 15

# Subtract and assign
x -= 3  # Same as: x = x - 3
print("After x -= 3:", x)  # 12

# Multiply and assign
x *= 2  # Same as: x = x * 2
print("After x *= 2:", x)  # 24

# Divide and assign
x /= 4  # Same as: x = x / 4
print("After x /= 4:", x)  # 6.0

# Modulus and assign
x %= 4  # Same as: x = x % 4
print("After x %= 4:", x)  # 2.0
