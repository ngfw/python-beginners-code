#!/usr/bin/env python3
"""
Chapter 4: Functions & Modules
Example 19: math Module Examples
"""

import math

print("=== Constants ===")
print("Pi:", math.pi)     # 3.14159...
print("e:", math.e)       # 2.71828...

print("\n=== Common functions ===")
print("sqrt(25):", math.sqrt(25))          # 5.0 (square root)
print("pow(2, 3):", math.pow(2, 3))        # 8.0 (2 to the power of 3)
print("ceil(4.2):", math.ceil(4.2))        # 5 (round up)
print("floor(4.8):", math.floor(4.8))      # 4 (round down)
print("factorial(5):", math.factorial(5))  # 120 (5!)

print("\n=== Trigonometry ===")
print("sin(pi/2):", math.sin(math.pi/2))  # 1.0
print("cos(0):", math.cos(0))             # 1.0
