#!/usr/bin/env python3
"""
Chapter 3: Control Flow
Example 3: if-elif-else for Grade Calculation
"""

score = 85

if score >= 90:
    print("Grade: A")
elif score >= 80:
    print("Grade: B")
elif score >= 70:
    print("Grade: C")
elif score >= 60:
    print("Grade: D")
else:
    print("Grade: F")
