#!/usr/bin/env python3
"""
Chapter 5: Data Structures
Example 15: Creating Dictionaries
"""

# Empty dictionary
empty_dict = {}
print("Empty dictionary:", empty_dict)

# Dictionary with data
student = {
    "name": "Alice",
    "age": 20,
    "grade": "A"
}
print("Student:", student)

# Using dict()
student2 = dict(name="Alice", age=20, grade="A")
print("Student2:", student2)
