#!/usr/bin/env python3
"""
Chapter 5: Data Structures
Example 2: Creating Lists
"""

# Empty list
empty_list = []
print("Empty list:", empty_list)

# List of numbers
numbers = [1, 2, 3, 4, 5]
print("Numbers:", numbers)

# List of strings
fruits = ["apple", "banana", "cherry"]
print("Fruits:", fruits)

# Mixed types (possible but not common)
mixed = [1, "hello", 3.14, True]
print("Mixed:", mixed)

# List with duplicates (allowed)
scores = [100, 85, 100, 90, 85]
print("Scores:", scores)
