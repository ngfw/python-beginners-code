#!/usr/bin/env python3
"""
Chapter 6: Working with Strings
Example 10: Old-Style String Formatting

Demonstrates the old % formatting method.
Note: This is legacy syntax; f-strings are preferred for new code.
"""

name = "Alice"
age = 25
print("My name is %s and I'm %d years old" % (name, age))
# My name is Alice and I'm 25 years old
