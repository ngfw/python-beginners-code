#!/usr/bin/env python3
"""
Chapter 6: Working with Strings
Example 2: String as a Sequence

Demonstrates accessing individual characters in strings:
- Indexing (positive and negative)
- Slicing
"""

word = "Python"
print(f"Word: {word}")
print(f"First character (word[0]): {word[0]}")   # P
print(f"Last character (word[-1]): {word[-1]}")  # n
print(f"Slice (word[1:4]): {word[1:4]}")  # yth
