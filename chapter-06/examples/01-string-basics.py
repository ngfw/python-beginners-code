#!/usr/bin/env python3
"""
Chapter 6: Working with Strings
Example 1: String Basics

Demonstrates different ways to create strings:
- Single and double quotes
- Multi-line strings with triple quotes
- Escaping characters
"""

# Single or double quotes (your choice)
message1 = 'Hello, World!'
message2 = "Hello, World!"

print("Single quotes:", message1)
print("Double quotes:", message2)

# Multi-line strings (triple quotes)
poem = """Roses are red,
Violets are blue,
Python is awesome,
And so are you!"""

print("\nMulti-line poem:")
print(poem)

# Escaping characters
quote = "She said, \"Hello!\""
path = "C:\\Users\\Alice\\Documents"

print("\nEscaped quote:", quote)
print("Windows path:", path)
